"""Простая локальная проверка на признаки кризиса.

Это страховка поверх системного промта: если в тексте явно есть слова о
самоубийстве или самоповреждении, бот не толкует сон, а отвечает бережно.
"""

import re

CRISIS_PATTERNS = [
    r"суицид",
    r"самоубийств",
    r"покончить\s+с\s+собой",
    r"убить\s+себя",
    r"убью\s+себя",
    r"не\s+хочу\s+(больше\s+)?жить",
    r"не\s+хочется\s+жить",
    r"хочу\s+умереть",
    r"лучше\s+бы\s+(я\s+)?(умер|умерла|не\s+жил)",
    r"режу\s+себя",
    r"резать\s+себя",
    r"порезать\s+себя",
    r"причинить\s+себе\s+вред",
    r"самоповрежд",
    r"селфхарм",
    r"\bsuicid",
    r"kill\s+myself",
    r"want\s+to\s+die",
    r"end\s+my\s+life",
    r"self[-\s]?harm",
    r"hurt\s+myself",
]

_CRISIS_RE = re.compile("|".join(CRISIS_PATTERNS), re.IGNORECASE)

CRISIS_REPLY = (
    "Мне кажется, сейчас вам по-настоящему тяжело, и я не хочу отвечать на это "
    "толкованием сна. То, что вы чувствуете, важно, и вы не обязаны справляться с этим "
    "в одиночку. Пожалуйста, поговорите с кем-то из близких, кому доверяете, или с "
    "психологом. В России можно бесплатно и анонимно позвонить на телефон доверия "
    "8-800-2000-122, круглосуточно. Если вы в опасности прямо сейчас, позвоните 112."
)


def looks_like_crisis(text: str) -> bool:
    return bool(_CRISIS_RE.search(text.replace("ё", "е").replace("Ё", "Е")))
